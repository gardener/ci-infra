package main

import (
	"os"
	"path/filepath"
	"strings"

	. "github.com/onsi/ginkgo/v2"
	. "github.com/onsi/gomega"
	"k8s.io/apimachinery/pkg/util/sets"
	"sigs.k8s.io/prow/pkg/github"
)

var _ = Describe("Generate", func() {
	Describe("eligibleRepos", func() {
		It("keeps only public, non-archived, non-fork repos and sorts them", func() {
			repos := []github.Repo{
				{Name: "zebra"},
				{Name: "alpha"},
				{Name: "secret", Private: true},
				{Name: "old", Archived: true},
				{Name: "mirror", Fork: true},
			}

			Expect(eligibleRepos(repos, "gardener", sets.New[string]())).To(Equal([]string{"alpha", "zebra"}))
		})

		It("excludes GitHub meta-repositories whose name starts with a dot", func() {
			repos := []github.Repo{
				{Name: ".github"},
				{Name: ".repository-template"},
				{Name: "gardener"},
			}

			Expect(eligibleRepos(repos, "gardener", sets.New[string]())).To(Equal([]string{"gardener"}))
		})

		It("excludes repos listed in skip", func() {
			repos := []github.Repo{
				{Name: "alpha"},
				{Name: "beta"},
			}

			skip := sets.New[string]("gardener/beta")
			Expect(eligibleRepos(repos, "gardener", skip)).To(Equal([]string{"alpha"}))
		})

		It("returns nil when no repo is eligible", func() {
			repos := []github.Repo{{Name: "secret", Private: true}}
			Expect(eligibleRepos(repos, "gardener", sets.New[string]())).To(BeNil())
		})
	})

	Describe("resolveImage", func() {
		var dir string

		BeforeEach(func() {
			dir = GinkgoT().TempDir()
		})

		It("prefers the image pinned in the existing file over the flag", func() {
			path := filepath.Join(dir, "renovate-presubmits.yaml")
			Expect(os.WriteFile(path, []byte("      - image: ghcr.io/renovatebot/renovate:99.9.9\n"), 0644)).To(Succeed())
			image, err := resolveImage(path, "ghcr.io/renovatebot/renovate:1.2.3")
			Expect(err).NotTo(HaveOccurred())
			Expect(image).To(Equal("ghcr.io/renovatebot/renovate:99.9.9"))
		})

		It("uses the flag when the file does not exist yet", func() {
			image, err := resolveImage(filepath.Join(dir, "missing.yaml"), "ghcr.io/renovatebot/renovate:1.2.3")
			Expect(err).NotTo(HaveOccurred())
			Expect(image).To(Equal("ghcr.io/renovatebot/renovate:1.2.3"))
		})

		It("uses the flag when the file exists but pins no image", func() {
			path := filepath.Join(dir, "other.yaml")
			Expect(os.WriteFile(path, []byte("some: value\n"), 0644)).To(Succeed())
			image, err := resolveImage(path, "ghcr.io/renovatebot/renovate:1.2.3")
			Expect(err).NotTo(HaveOccurred())
			Expect(image).To(Equal("ghcr.io/renovatebot/renovate:1.2.3"))
		})

		It("errors when neither the file nor the flag provides an image", func() {
			_, err := resolveImage(filepath.Join(dir, "missing.yaml"), "")
			Expect(err).To(HaveOccurred())
		})

		It("returns a read error that is not a missing file", func() {
			// A directory cannot be read as a file, so os.ReadFile returns a non-NotExist error.
			_, err := resolveImage(dir, "ghcr.io/renovatebot/renovate:1.2.3")
			Expect(err).To(HaveOccurred())
		})
	})

	Describe("renderPresubmits", func() {
		It("renders the first repo as a YAML anchor with the full job definition", func() {
			content, err := renderPresubmits("gardener", "gardener-prow-build", "ghcr.io/renovatebot/renovate:1.2.3", []string{"ci-infra", "gardener"})
			Expect(err).NotTo(HaveOccurred())

			rendered := string(content)
			Expect(rendered).To(ContainSubstring("# This file is generated by the renovate-presubmit-generator. DO NOT EDIT."))
			Expect(rendered).To(ContainSubstring("presubmits:"))
			Expect(rendered).To(ContainSubstring("  gardener/ci-infra:"))
			Expect(rendered).To(ContainSubstring("  - &renovate-presubmit"))
			Expect(rendered).To(ContainSubstring("    name: pull-ci-infra-check-renovate-config"))
			Expect(rendered).To(ContainSubstring("    cluster: gardener-prow-build"))
			Expect(rendered).To(ContainSubstring("      - image: ghcr.io/renovatebot/renovate:1.2.3"))
			Expect(rendered).To(ContainSubstring("        - renovate-config-validator"))
			Expect(rendered).To(ContainSubstring("    run_if_changed: '" + runIfChanged + "'"))
		})

		It("renders subsequent repos by merging the anchor and only overriding the name", func() {
			content, err := renderPresubmits("gardener", "gardener-prow-build", "image:1", []string{"ci-infra", "gardener"})
			Expect(err).NotTo(HaveOccurred())

			rendered := string(content)
			Expect(rendered).To(ContainSubstring("  gardener/gardener:"))
			Expect(rendered).To(ContainSubstring("  - <<: *renovate-presubmit"))
			Expect(rendered).To(ContainSubstring("    name: pull-gardener-check-renovate-config"))
			// The anchor is defined exactly once and the full definition (the command) is not repeated.
			Expect(strings.Count(rendered, "&renovate-presubmit")).To(Equal(1))
			Expect(strings.Count(rendered, "- renovate-config-validator")).To(Equal(1))
		})

		It("renders repos in the given order", func() {
			content, err := renderPresubmits("gardener", "gardener-prow-build", "image:1", []string{"alpha", "beta"})
			Expect(err).NotTo(HaveOccurred())

			rendered := string(content)
			Expect(rendered).To(MatchRegexp(`(?s)gardener/alpha:.*gardener/beta:`))
		})

		It("renders an empty presubmit block when there are no repos", func() {
			content, err := renderPresubmits("gardener", "gardener-prow-build", "image:1", nil)
			Expect(err).NotTo(HaveOccurred())
			Expect(string(content)).To(ContainSubstring("presubmits:"))
			Expect(string(content)).NotTo(ContainSubstring("name: pull-"))
			Expect(string(content)).NotTo(ContainSubstring("&renovate-presubmit"))
		})
	})
})
